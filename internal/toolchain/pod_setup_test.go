// repositoryRoot returns the root of the repository, computed from the
// location of this file, so the checks below never depend on the working
// directory of the test binary.
func repositoryRoot(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate the test source file")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(file), "..", ".."))
}

// setupScript returns the path of the pod setup script.
func setupScript(t *testing.T) string {
	t.Helper()
	return filepath.Join(repositoryRoot(t), ".optio", "setup.sh")
}

// platformKey returns the mise platform key of the running machine and the
// name of the official archive for it. The test computes them independently
// from the script, so a wrong mapping in the script is caught here.
func platformKey(t *testing.T) (key, archive string) {
	t.Helper()
	switch runtime.GOOS + "/" + runtime.GOARCH {
	case "linux/amd64":
		return "linux-x64", "linux-amd64"
	case "linux/arm64":
		return "linux-arm64", "linux-arm64"
	case "darwin/arm64":
		return "macos-arm64", "darwin-arm64"
	case "darwin/amd64":
		return "macos-x64", "darwin-amd64"
	}
	t.Skipf("no official Go archive pinned for %s/%s", runtime.GOOS, runtime.GOARCH)
	return "", ""
}

// fakeToolchain describes the toolchain the setup script installs in a
// throwaway repository.
type fakeToolchain struct {
	repo    string // throwaway repository holding go.mod, mise.lock and the script
	mirror  string // directory serving the archive over the file:// protocol
	home    string // fake HOME of the installation
	version string // Go version required by the fake go.mod
}

// goBinary returns the path of the installed go command.
func (f fakeToolchain) goBinary() string {
	return filepath.Join(f.home, ".local", "optio", "go", "bin", "go")
}

// shim returns the path of the go command exposed on the PATH.
func (f fakeToolchain) shim() string {
	return filepath.Join(f.home, ".local", "bin", "go")
}

// writeArchive writes a tarball holding a go command reporting the given
// version, and returns its sha256.
func writeArchive(t *testing.T, path, version string) string {
	t.Helper()
	body := fmt.Sprintf("#!/bin/sh\ncase \"$1\" in\n  version) echo \"go version go%s linux/amd64\" ;;\nesac\nexit 0\n", version)
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for _, entry := range []struct{ name, content string }{
		{"go/bin/go", body},
		{"go/bin/gofmt", "#!/bin/sh\nexit 0\n"},
	} {
		header := &tar.Header{
			Name:     entry.name,
			Mode:     0o755,
			Size:     int64(len(entry.content)),
			Typeflag: tar.TypeReg,
		}
		if err := tw.WriteHeader(header); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write([]byte(entry.content)); err != nil {
			t.Fatal(err)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := gz.Close(); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	return sha256Of(t, path)
}

// sha256Of returns the sha256 of a file.
func sha256Of(t *testing.T, path string) string {
	t.Helper()
	for _, command := range [][]string{{"sha256sum", path}, {"shasum", "-a", "256", path}} {
		out, err := exec.Command(command[0], command[1:]...).Output()
		if err != nil {
			continue
		}
		return strings.Fields(string(out))[0]
	}
	t.Fatalf("no sha256 tool available to hash %s", path)
	return ""
}

// newFakeToolchain builds a throwaway repository served by a local mirror.
// The archive it serves is a stub, so the test never reaches the network.
// The checksum of mise.lock matches the served archive, unless the test asks
// for a wrong one.
func newFakeToolchain(t *testing.T, version string, wrongChecksum bool) fakeToolchain {
	t.Helper()
	key, archive := platformKey(t)
	root := t.TempDir()
	fake := fakeToolchain{
		repo:    filepath.Join(root, "repo"),
		mirror:  filepath.Join(root, "mirror"),
		home:    filepath.Join(root, "home"),
		version: version,
	}
	for _, dir := range []string{filepath.Join(fake.repo, ".optio"), fake.mirror, fake.home} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	module := fmt.Sprintf("module example.com/fake\n\ngo %s\n", version)
	if err := os.WriteFile(filepath.Join(fake.repo, "go.mod"), []byte(module), 0o644); err != nil {
		t.Fatal(err)
	}
	checksum := writeArchive(t, filepath.Join(fake.mirror, fmt.Sprintf("go%s.%s.tar.gz", version, archive)), version)
	if wrongChecksum {
		checksum = strings.Repeat("0", 64)
	}
	lock := fmt.Sprintf(`# @generated - this file is auto-generated by `+"`mise lock`"+`

[[tools.go]]
version = "%s"
backend = "core:go"

[tools.go."platforms.%s"]
checksum = "sha256:%s"
url = "https://dl.google.com/go/go%s.%s.tar.gz"
`, version, key, checksum, version, archive)
	if err := os.WriteFile(filepath.Join(fake.repo, "mise.lock"), []byte(lock), 0o644); err != nil {
		t.Fatal(err)
	}
	script, err := os.ReadFile(setupScript(t))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(fake.repo, ".optio", "setup.sh"), script, 0o755); err != nil {
		t.Fatal(err)
	}
	return fake
}

// run executes the setup script of the fake repository.
func (f fakeToolchain) run(t *testing.T, strict bool, extra ...string) (int, string, string) {
	t.Helper()
	env := []string{
		"HOME=" + f.home,
		"PATH=" + filepath.Join(f.home, ".local", "bin") + ":" + os.Getenv("PATH"),
		"TMPDIR=" + os.TempDir(),
		"OPTIO_GO_DOWNLOAD_BASE_URL=file://" + f.mirror,
	}
	if strict {
		env = append(env, "OPTIO_SETUP_STRICT=1")
	}
	env = append(env, extra...)
	cmd := exec.Command("bash", filepath.Join(f.repo, ".optio", "setup.sh"))
	cmd.Env = env
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	err := cmd.Run()
	code := 0
	if err != nil {
		var exitErr *exec.ExitError
		if !errors.As(err, &exitErr) {
			t.Fatalf("cannot run the setup script: %v", err)
		}
		code = exitErr.ExitCode()
	}
	return code, stdout.String(), stderr.String()
}

// The Go version of go.mod is the reference of the toolchain contract, and
// mise.lock must pin exactly that version, with the official archives and
// their checksums.
func TestMiseLockPinsTheGoVersionRequiredByGoMod(t *testing.T) {
	root := repositoryRoot(t)
	module, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	version := regexp.MustCompile(`(?m)^go\s+(\S+)`).FindStringSubmatch(string(module))
	if version == nil {
		t.Fatal("go.mod has no go directive")
	}
	lock, err := os.ReadFile(filepath.Join(root, "mise.lock"))
	if err != nil {
		t.Fatal(err)
	}
	pinned := regexp.MustCompile(`(?m)^\[\[tools\.go\]\]\s*\nversion\s*=\s*"([^"]+)"`).FindStringSubmatch(string(lock))
	if pinned == nil {
		t.Fatal("mise.lock pins no go version")
	}
	if pinned[1] != version[1] {
		t.Fatalf("mise.lock pins go %s but go.mod requires %s", pinned[1], version[1])
	}
	archives := regexp.MustCompile(`(?m)^\[tools\.go\."platforms\.[^"]+"\]\s*\nchecksum\s*=\s*"sha256:([0-9a-f]{64})"\s*\nurl\s*=\s*"([^"]+)"`).FindAllStringSubmatch(string(lock), -1)
	if len(archives) == 0 {
		t.Fatal("mise.lock pins no platform archive")
	}
	for _, archive := range archives {
		if !strings.HasPrefix(archive[2], "https://dl.google.com/go/") {
			t.Errorf("archive %s does not come from the official Go download", archive[2])
		}
		if !strings.Contains(archive[2], version[1]) {
			t.Errorf("archive %s does not match the go version %s", archive[2], version[1])
		}
	}
}

// The setup script must take the version from go.mod and the checksum from
// mise.lock: a checksum written in the script would drift from the lock file
// and could not be refreshed by `mise lock`.
func TestPodSetupReadsTheVersionAndTheChecksumFromTheRepository(t *testing.T) {
	script, err := os.ReadFile(setupScript(t))
	if err != nil {
		t.Fatal(err)
	}
	content := string(script)
	for _, expected := range []string{"go.mod", "mise.lock", "https://dl.google.com/go"} {
		if !strings.Contains(content, expected) {
			t.Errorf("the setup script does not use %s", expected)
		}
	}
	if regexp.MustCompile(`(?i)[0-9a-f]{64}`).MatchString(content) {
		t.Error("the setup script hardcodes a checksum instead of reading mise.lock")
	}
	if strings.Contains(content, "/usr/local") {
		t.Error("the setup script writes outside of the home directory")
	}
}

// The pod image gives no privileged command to the agent: the setup script
// must not rely on a package manager to install the toolchain.
func TestPodSetupUsesNoPrivilegedCommand(t *testing.T) {
	script, err := os.ReadFile(setupScript(t))
	if err != nil {
		t.Fatal(err)
	}
	commands := regexp.MustCompile(`(?m)^\s*(sudo|apt|apt-get|yum|dnf|apk|pacman|brew|chown|useradd|usermod)\b`)
	for _, match := range commands.FindAllString(stripComments(string(script)), -1) {
		t.Errorf("the setup script runs the privileged command %q", strings.TrimSpace(match))
	}
}

// stripComments removes the comment lines of a shell script.
func stripComments(script string) string {
	lines := strings.Split(script, "\n")
	kept := make([]string, 0, len(lines))
	for _, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "#") {
			continue
		}
		kept = append(kept, line)
	}
	return strings.Join(kept, "\n")
}

// The script installs the toolchain of go.mod, verifies the checksum of the
// archive before extracting it, and exposes it on the PATH.
func TestPodSetupInstallsTheVerifiedToolchain(t *testing.T) {
	fake := newFakeToolchain(t, "1.23.9", false)

	code, stdout, stderr := fake.run(t, true)
	if code != 0 {
		t.Fatalf("the setup script failed with %d: %s%s", code, stdout, stderr)
	}
	if !strings.Contains(stdout, "checksum verified") {
		t.Errorf("the setup script does not report the checksum verification: %s", stdout)
	}
	if _, err := os.Stat(fake.goBinary()); err != nil {
		t.Fatalf("the toolchain is not installed: %v", err)
	}
	version, err := exec.Command(fake.goBinary(), "version").Output()
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(version), "go1.23.9") {
		t.Errorf("the installed toolchain reports %q", version)
	}
	target, err := os.Readlink(fake.shim())
	if err != nil {
		t.Fatalf("the setup script does not expose the toolchain on the PATH: %v", err)
	}
	if target != fake.goBinary() {
		t.Errorf("the shim points to %s", target)
	}
}

// Re-running the script on an up-to-date installation must change nothing:
// the toolchain is already there and nothing is downloaded again, even when
// the archive is unreachable.
func TestPodSetupIsIdempotent(t *testing.T) {
	fake := newFakeToolchain(t, "1.23.9", false)

	if code, stdout, stderr := fake.run(t, true); code != 0 {
		t.Fatalf("the first run failed with %d: %s%s", code, stdout, stderr)
	}
	if err := os.RemoveAll(fake.mirror); err != nil {
		t.Fatal(err)
	}
	code, stdout, stderr := fake.run(t, true)
	if code != 0 {
		t.Fatalf("the second run failed with %d: %s%s", code, stdout, stderr)
	}
	if !strings.Contains(stdout, "already installed") {
		t.Errorf("the second run did not detect the existing toolchain: %s", stdout)
	}
	if _, err := os.Stat(fake.goBinary()); err != nil {
		t.Fatalf("the toolchain disappeared: %v", err)
	}
}

// An archive whose checksum does not match mise.lock must be refused: the
// toolchain is never extracted and never installed.
func TestPodSetupRefusesAnArchiveWithAWrongChecksum(t *testing.T) {
	fake := newFakeToolchain(t, "1.23.9", true)

	code, stdout, stderr := fake.run(t, true)
	if code == 0 {
		t.Fatalf("the setup script accepted an archive with a wrong checksum: %s", stdout)
	}
	if !strings.Contains(stderr, "checksum mismatch") {
		t.Errorf("the setup script does not report the checksum mismatch: %s", stderr)
	}
	if _, err := os.Stat(fake.goBinary()); err == nil {
		t.Error("the toolchain was installed from an unverified archive")
	}
}

// The toolchain belongs to the home directory of the agent: the script
// refuses any other location, it would write outside of the pod home.
func TestPodSetupRefusesAnInstallationOutsideOfTheHome(t *testing.T) {
	fake := newFakeToolchain(t, "1.23.9", false)
	outside := filepath.Join(t.TempDir(), "go")

	code, stdout, stderr := fake.run(t, true, "OPTIO_GO_INSTALL_ROOT="+outside)
	if code == 0 {
		t.Fatalf("the setup script accepted an installation outside of the home: %s", stdout)
	}
	if !strings.Contains(stderr, "outside of") {
		t.Errorf("the setup script does not report the refused location: %s", stderr)
	}
	if _, err := os.Stat(outside); err == nil {
		t.Error("the toolchain was installed outside of the home directory")
	}
}

// The pod must start even when the setup fails: /opt/optio/repo-init.sh runs
// with `set -e`, so a non-zero status would keep the pod from starting.
func TestPodSetupNeverStopsThePod(t *testing.T) {
	fake := newFakeToolchain(t, "1.23.9", false)
	if err := os.Remove(filepath.Join(fake.repo, "mise.lock")); err != nil {
		t.Fatal(err)
	}

	code, stdout, stderr := fake.run(t, false)
	if code != 0 {
		t.Fatalf("the setup script returned %d, the pod would not start: %s%s", code, stdout, stderr)
	}
	if !strings.Contains(stderr, "ERROR") {
		t.Errorf("the setup script does not report the failure: %s", stderr)
	}
}

